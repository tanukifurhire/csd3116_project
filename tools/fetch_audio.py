#!/usr/bin/env python3
"""fetch_audio.py -- fetch the recorded sound layers for audio/ into assets/audio/.

    python3 tools/fetch_audio.py [--out assets] [--build build] [--offline]

Engines, nitro and the procedural parts of the impacts are synthesised at run
time (audio/src); these recordings only add realism on top:

  skid_loop.wav        "Car tire squeal skid loop" by audible-edge (Tom Haigh),
                       submitted by qubodup -- CC-BY 3.0
                       https://opengameart.org/content/car-tire-squeal-skid-loop
  bump_*.ogg,          "75 CC0 breaking / falling / hit sfx" by rubberduck -- CC0
  crash_metal_*.ogg,   https://opengameart.org/content/75-cc0-breaking-falling-hit-sfx
  crash_crunch_*.ogg
  thud_*.wav           "Metal Impact Sounds" by BMacZero -- CC0
                       https://opengameart.org/content/metal-impact-sounds

Downloads are cached in build/audio_src/. Like the other fetched assets they
are never committed. Any failure only prints a note: the game then uses the
procedural versions. Stdlib only.
"""

import argparse
import os
import shutil
import sys
import urllib.request
import zipfile

BASE = "https://opengameart.org/sites/default/files/"
UA = "Mozilla/5.0 (X11; Linux x86_64) drifto-asset-fetch"

FILES = {
    "tires_squal_loop.wav": "tires_squal_loop.wav",
    "sfx_breaking_and_falling.zip": "sfx_breaking_and_falling.zip",
    "thud2.wav": "thud2.wav",
}

# zip member -> asset name, picked with `audio_demo --analyze` (duration,
# spectral centroid, low-frequency share, decay):
ZIP_MAP = {
    # car-on-car bumps: low, body-panel knocks (centroid 150-700 Hz)
    "bfh1_hit_02.ogg": "bump_1.ogg",
    "bfh1_hit_07.ogg": "bump_2.ogg",
    "bfh1_hit_06.ogg": "bump_3.ogg",
    "bfh1_metal_hit_04.ogg": "bump_4.ogg",
    # barrier crash: metal impacts + heavy low metal hit
    "bfh1_metal_hit_02.ogg": "crash_metal_1.ogg",
    "bfh1_metal_hit_06.ogg": "crash_metal_2.ogg",
    "bfh1_metal_hit_03.ogg": "crash_metal_3.ogg",
    "bfh1_metal_hit_05.ogg": "crash_metal_4.ogg",
    # debris / crunch tails
    "bfh1_metal_falling_02.ogg": "crash_crunch_1.ogg",
    "bfh1_metal_falling_01.ogg": "crash_crunch_2.ogg",
    "bfh1_breaking_03.ogg": "crash_crunch_3.ogg",
}

CREDITS = """Drifto audio -- generated by tools/fetch_audio.py (fetched at build time,
not redistributed with the source).

Synthesised at run time (audio/src, no recordings): engines (AE86 4A-GE and
RX7 13B rotary firing models), nitro ignite/burn, procedural layers of the
bump/crash/scrape sounds, and the tyre squeal fallback.

Recorded layers:
  skid_loop.wav       "Car tire squeal skid loop" by audible-edge (Tom Haigh),
                      submitted by qubodup. License: CC-BY 3.0
                      https://opengameart.org/content/car-tire-squeal-skid-loop
  bump_*.ogg, crash_metal_*.ogg, crash_crunch_*.ogg
                      "75 CC0 breaking / falling / hit sfx" by rubberduck. License: CC0
                      https://opengameart.org/content/75-cc0-breaking-falling-hit-sfx
  thud_*.wav          "Metal Impact Sounds" by BMacZero. License: CC0
                      https://opengameart.org/content/metal-impact-sounds
"""


def log(*a):
    print("[audio]", *a, flush=True)


def download(name, cache, offline):
    path = os.path.join(cache, name)
    if os.path.exists(path):
        return path
    if offline:
        return None
    try:
        req = urllib.request.Request(BASE + name, headers={"User-Agent": UA})
        with urllib.request.urlopen(req, timeout=60) as r, open(path + ".part", "wb") as f:
            shutil.copyfileobj(r, f)
        os.replace(path + ".part", path)
        return path
    except Exception as e:
        log("could not fetch %s (%s) -- procedural fallback" % (name, e))
        return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="assets")
    ap.add_argument("--build", default="build")
    ap.add_argument("--offline", action="store_true")
    args = ap.parse_args()
    cache = os.path.join(args.build, "audio_src")
    dst = os.path.join(args.out, "audio")
    os.makedirs(cache, exist_ok=True)
    os.makedirs(dst, exist_ok=True)
    n = 0
    p = download("tires_squal_loop.wav", cache, args.offline)
    if p:
        shutil.copyfile(p, os.path.join(dst, "skid_loop.wav"))
        n += 1
    p = download("thud2.wav", cache, args.offline)
    if p:
        shutil.copyfile(p, os.path.join(dst, "thud_1.wav"))
        n += 1
    p = download("sfx_breaking_and_falling.zip", cache, args.offline)
    if p:
        try:
            with zipfile.ZipFile(p) as z:
                names = set(z.namelist())
                for src, out in ZIP_MAP.items():
                    if src in names:
                        with z.open(src) as fi, open(os.path.join(dst, out), "wb") as fo:
                            shutil.copyfileobj(fi, fo)
                        n += 1
        except zipfile.BadZipFile:
            log("bad zip %s" % p)
    with open(os.path.join(dst, "CREDITS.txt"), "w") as f:
        f.write(CREDITS)
    log("%d recorded sounds -> %s" % (n, dst))
    return 0


if __name__ == "__main__":
    sys.exit(main())
