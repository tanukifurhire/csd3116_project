def log(*a):
    print("[hud]", *a, flush=True)


def fetch(build, offline):
    os.makedirs(build, exist_ok=True)
    tar = os.path.join(build, "initial-d-hud.tar.gz")
    if not os.path.exists(tar):
        if offline:
            return None
        log("downloading", URL)
        try:
            with urllib.request.urlopen(URL, timeout=60) as r, open(tar + ".part", "wb") as f:
                shutil.copyfileobj(r, f)
            os.replace(tar + ".part", tar)
        except Exception as e:  # network down etc: keep the built-in theme
            log("download failed (%s); the built-in 'drifto_arcade' HUD theme will be used" % e)
            return None
    return tar


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="assets")
    ap.add_argument("--build", default="build")
    ap.add_argument("--offline", action="store_true")
    args = ap.parse_args()

    dst = os.path.join(args.out, "hud", "initiald")
    theme_path = os.path.join(dst, "theme.txt")
    if os.path.exists(theme_path) and STAMP in open(theme_path).read():
        return 0
    tar = fetch(args.build, args.offline)
    if not tar:
        return 0
    os.makedirs(dst, exist_ok=True)
    n = 0
    with tarfile.open(tar, "r:gz") as tf:
        for m in tf.getmembers():
            parts = m.name.split("/")
            if not m.isfile() or "img" not in parts or not m.name.lower().endswith(".png"):
                continue
            rel = "/".join(parts[parts.index("img") + 1:])
            out = os.path.join(dst, rel)
            os.makedirs(os.path.dirname(out), exist_ok=True)
            with tf.extractfile(m) as src, open(out, "wb") as f:
                shutil.copyfileobj(src, f)
            n += 1
    if n == 0:
        log("no web/img/*.png in the tarball -- layout changed? keeping the built-in theme")
        return 0
    with open(theme_path, "w") as f:
        f.write(THEME.format(stamp=STAMP, url=URL))
    with open(os.path.join(dst, "CREDITS.txt"), "w") as f:
        f.write("Initial D arcade HUD sprites by mxet_ -- https://github.com/xmatheusgc/Initial-D-HUD\n"
                "No license; fetched at build time for private use. Do not redistribute or commit.\n")
    log("installed %d sprites -> %s" % (n, dst))
    return 0


if __name__ == "__main__":
    sys.exit(main())
